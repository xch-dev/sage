#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;
    #[test]
    fn every_rpc_endpoint_has_an_explicit_policy() {
        let api: serde_json::Map<String, serde_json::Value> =
            serde_json::from_str(include_str!("../../sage-api/endpoints.json")).unwrap();
        let methods: BTreeSet<_> = RPC_POLICIES.iter().map(|p| p.method).collect();
        assert_eq!(methods.len(), RPC_POLICIES.len(), "duplicate RPC policy");
        assert_eq!(methods, api.keys().map(String::as_str).collect());
        for policy in RPC_POLICIES {
            if let Some(cap) = policy.capability {
                assert!(WalletCapability::ALL.contains(&cap));
            }
        }
        assert!(rpc_policy("unknown_future_method").is_none());
    }
}
