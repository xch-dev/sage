//! Explicit policy for every public HTTP RPC endpoint. Apps can expose a subset.
use crate::WalletCapability;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RpcScope {
    Global,
    ActiveWallet,
    TargetWallet,
    WalletList,
}

#[derive(Debug, Clone, Copy)]
pub struct RpcPolicy {
    pub method: &'static str,
    /// None means owner credentials only, never grantable to a scoped client.
    pub capability: Option<WalletCapability>,
    pub scope: RpcScope,
    pub approval: bool,
    pub category: &'static str,
}

pub fn rpc_policy(method: &str) -> Option<&'static RpcPolicy> {
    RPC_POLICIES.iter().find(|policy| policy.method == method)
}

